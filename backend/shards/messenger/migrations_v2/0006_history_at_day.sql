-- Ревью 7 ноя 2026 (S7-3): время записи журнала истории — только сутки. Точное время записи рядом с временем
-- доставки в инбоксы (`inbox_log`) выдавало автора личного сообщения и автора в группе; поле ни для чего не
-- используется. Новые записи шард пишет уже округлёнными (`v2_history.rs record_day`).
UPDATE user_history_log SET at = (at / 86400) * 86400 WHERE at % 86400 != 0;
