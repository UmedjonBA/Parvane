-- Копия корня пользователя, запечатанная открытым ключом администратора сервера
-- (HPKE, recovery.rs seal_root_escrow). Страховка на случай, когда потеряны и все
-- устройства, и ключ восстановления: администратор открывает копию СВОИМ закрытым
-- ключом (на сервере его нет) и выписывает пользователю новый ключ восстановления.
CREATE TABLE root_escrow (
    user       TEXT PRIMARY KEY,
    escrow     BLOB NOT NULL,
    updated_at INTEGER NOT NULL
);
