-- FR-066 (D-12), T130: копия корня пользователя под ключом восстановления
-- (≥ 128 бит, генерируется клиентом). Сервер хранит только шифртекст — без
-- ключа восстановления он бесполезен. Нужна новому устройству, когда других
-- устройств аккаунта не осталось.
CREATE TABLE root_backup (
    user       TEXT PRIMARY KEY,
    backup     BLOB NOT NULL,
    updated_at INTEGER NOT NULL
);
