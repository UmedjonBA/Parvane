-- вместе с хэшем пароля при входе (claim `cg`). Токен с `cg` меньше текущего недействителен (кроме устройства,
-- сменившего пароль), — точное сравнение вместо `iat < password_changed_at` с точностью до секунды и без гонки
-- «пароль проверен → пароль сменён → токен выдан». Прежние строки получают 0: токены без `cg` проверяются
-- по-старому, по секундам (через сутки таких токенов не останется).
ALTER TABLE users ADD COLUMN cred_gen INTEGER NOT NULL DEFAULT 0;
